#!/usr/bin/env node
/**
 * Generates drizzle/0023_schema_reconcile.sql and drizzle/0024_hot_indexes.sql from a fresh
 * drizzle-kit full-schema dump (pass its path as argv[2]).
 *
 * 0023 makes ANY database — empty, or production with years of hand-applied drift — match
 * drizzle/schema.ts:  CREATE TABLE IF NOT EXISTS for every table, then a guarded ADD COLUMN
 * for every column of every table, then targeted enum/nullability MODIFYs. 0024 adds the hot
 * indexes and the new unique keys (deduping first). Everything is idempotent.
 */
import fs from "node:fs";

const kitPath = process.argv[2];
const kit = fs.readFileSync(kitPath, "utf8");
const stmts = kit.split("--> statement-breakpoint").map(s => s.trim()).filter(Boolean);

const esc = (s) => s.replace(/'/g, "''");
const guard = (cond, ddl) =>
  `SET @q = IF(${cond},\n  '${esc(ddl)}', 'SELECT 1');\nPREPARE s FROM @q;\nEXECUTE s;\nDEALLOCATE PREPARE s;`;

const colMissing = (t, c) =>
  `(SELECT COUNT(*) FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = '${t}' AND COLUMN_NAME = '${c}') = 0`;
const colExists = (t, c) =>
  `(SELECT COUNT(*) FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = '${t}' AND COLUMN_NAME = '${c}') = 1`;
const idxMissing = (t, i) =>
  `(SELECT COUNT(*) FROM information_schema.STATISTICS WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = '${t}' AND INDEX_NAME = '${i}') = 0`;

const tables = {};        // name -> { createSql, cols: [{name, def}], uniques: [{name, cols}] }
const kitIndexes = [];    // { name, table, cols, unique }

for (const st of stmts) {
  let m = st.match(/^CREATE TABLE `([^`]+)` \(([\s\S]*)\);?$/);
  if (m) {
    const name = m[1];
    const body = m[2];
    const cols = [];
    const uniques = [];
    for (let line of body.split("\n")) {
      line = line.trim().replace(/,$/, "");
      if (!line) continue;
      const cm = line.match(/^`([^`]+)` (.+)$/);
      if (cm) { cols.push({ name: cm[1], def: line }); continue; }
      const um = line.match(/^CONSTRAINT `([^`]+)` UNIQUE\(([^)]+)\)$/);
      if (um) { uniques.push({ name: um[1], cols: um[2] }); continue; }
      // PRIMARY KEY constraint line — ignored (new tables get it from CREATE; existing tables have it)
    }
    tables[name] = { createSql: st.replace(/^CREATE TABLE /, "CREATE TABLE IF NOT EXISTS "), cols, uniques };
    continue;
  }
  m = st.match(/^CREATE (UNIQUE )?INDEX `([^`]+)` ON `([^`]+)` \((.+)\);?$/);
  if (m) { kitIndexes.push({ unique: !!m[1], name: m[2], table: m[3], cols: m[4] }); continue; }
  throw new Error("Unrecognised statement: " + st.slice(0, 80));
}

// ── 0023 ─────────────────────────────────────────────────────────────────────
let out = [];
out.push(`-- 0023: schema reconcile — make ANY database (empty, or production with hand-applied drift) match
-- drizzle/schema.ts. Generated by scripts/dev/gen-reconcile.mjs from a fresh drizzle-kit dump; do not
-- hand-edit table/column blocks — regenerate instead. Three layers, each idempotent:
--   1. CREATE TABLE IF NOT EXISTS for every table (covers the ~44 tables no migration ever created)
--   2. guarded ADD COLUMN for every column of every table (covers columns added by one-off scripts)
--   3. targeted enum / nullability fixes (status enums, users.role, candidates.email, column widenings)
-- MySQL 8 / TiDB. NOT NULL columns added to non-empty tables fill with the type's zero value.`);
out.push("");
out.push("-- ── 1. tables ──");
for (const name of Object.keys(tables).sort()) {
  out.push(tables[name].createSql + (tables[name].createSql.trimEnd().endsWith(";") ? "" : ";"));
}
out.push("");
out.push("-- ── 2. columns ──");
for (const name of Object.keys(tables).sort()) {
  for (const col of tables[name].cols) {
    // Never ADD an AUTO_INCREMENT column — it must be a key, so a fired guard would abort the run.
    // Every existing table already has its id; new tables get it from CREATE above.
    if (/AUTO_INCREMENT/.test(col.def)) continue;
    out.push(guard(colMissing(name, col.name), `ALTER TABLE \`${name}\` ADD COLUMN ${col.def}`));
  }
}
out.push("");
out.push("-- ── 3. targeted fixes ──");
const colDef = (t, c) => {
  const hit = tables[t].cols.find(x => x.name === c);
  if (!hit) throw new Error(`no ${t}.${c}`);
  return hit.def;
};
// status enums: sentinel 'hired' (newest value) — MODIFY to the full list when it is missing
for (const [t, c] of [["candidates", "status"], ["stage_notes", "stage"]]) {
  out.push(guard(
    `${colExists(t, c)} AND (SELECT COUNT(*) FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = '${t}' AND COLUMN_NAME = '${c}' AND COLUMN_TYPE LIKE '%hired%') = 0`,
    `ALTER TABLE \`${t}\` MODIFY COLUMN ${colDef(t, c)}`
  ));
}
// users.role: sentinel 'owner'
out.push(guard(
  `${colExists("users", "role")} AND (SELECT COUNT(*) FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'users' AND COLUMN_NAME = 'role' AND COLUMN_TYPE LIKE '%owner%') = 0`,
  `ALTER TABLE \`users\` MODIFY COLUMN ${colDef("users", "role")}`
));
// leave_requests.status: sentinel 'cancelled'
out.push(guard(
  `${colExists("leave_requests", "status")} AND (SELECT COUNT(*) FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'leave_requests' AND COLUMN_NAME = 'status' AND COLUMN_TYPE LIKE '%cancelled%') = 0`,
  `ALTER TABLE \`leave_requests\` MODIFY COLUMN ${colDef("leave_requests", "status")}`
));
// agent_notifications.type: sentinel 'payment_missing'
out.push(guard(
  `${colExists("agent_notifications", "type")} AND (SELECT COUNT(*) FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'agent_notifications' AND COLUMN_NAME = 'type' AND COLUMN_TYPE LIKE '%payment_missing%') = 0`,
  `ALTER TABLE \`agent_notifications\` MODIFY COLUMN ${colDef("agent_notifications", "type")}`
));
// candidates.email nullable
out.push(guard(
  `(SELECT COUNT(*) FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'candidates' AND COLUMN_NAME = 'email' AND IS_NULLABLE = 'NO') = 1`,
  `ALTER TABLE \`candidates\` MODIFY COLUMN ${colDef("candidates", "email")}`
));
// agent_presence.traineeCode widen to 100
out.push(guard(
  `(SELECT COUNT(*) FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'agent_presence' AND COLUMN_NAME = 'traineeCode' AND CHARACTER_MAXIMUM_LENGTH < 100) = 1`,
  `ALTER TABLE \`agent_presence\` MODIFY COLUMN ${colDef("agent_presence", "traineeCode")}`
));
// agent_shifts.durationMs widen to bigint (0017 did it on prod; fresh DBs get it from CREATE)
out.push(guard(
  `(SELECT COUNT(*) FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'agent_shifts' AND COLUMN_NAME = 'durationMs' AND DATA_TYPE = 'int') = 1`,
  `ALTER TABLE \`agent_shifts\` MODIFY COLUMN ${colDef("agent_shifts", "durationMs")}`
));
fs.writeFileSync("drizzle/0023_schema_reconcile.sql", out.join("\n") + "\n");

// ── 0024 ─────────────────────────────────────────────────────────────────────
let o2 = [];
o2.push(`-- 0024: hot-path indexes + new unique keys. Generated by scripts/dev/gen-reconcile.mjs; guarded and
-- re-runnable. Duplicate rows are collapsed BEFORE each new unique key so the ALTER cannot fail.`);
o2.push("");
o2.push("-- dedupe before the new unique keys (keep the newest row)");
o2.push(`DELETE lb FROM leave_balances lb JOIN leave_balances lb2 ON lb.traineeCode = lb2.traineeCode AND lb.year = lb2.year AND lb.id < lb2.id;`);
o2.push(`DELETE bc FROM batch_candidates bc JOIN batch_candidates bc2 ON bc.batchId = bc2.batchId AND bc.candidateId = bc2.candidateId AND bc.id < bc2.id;`);
o2.push(`DELETE it FROM integrations_tokens it JOIN integrations_tokens it2 ON it.provider = it2.provider AND ((it.userId IS NULL AND it2.userId IS NULL) OR it.userId = it2.userId) AND it.id < it2.id;`);
o2.push("");
for (const ix of kitIndexes) {
  o2.push(guard(idxMissing(ix.table, ix.name), `CREATE ${ix.unique ? "UNIQUE " : ""}INDEX \`${ix.name}\` ON \`${ix.table}\` (${ix.cols})`));
}
o2.push("");
o2.push("-- unique keys that live inline in CREATE TABLE (added here for tables that pre-exist)");
for (const name of Object.keys(tables).sort()) {
  for (const u of tables[name].uniques) {
    o2.push(guard(idxMissing(name, u.name), `ALTER TABLE \`${name}\` ADD UNIQUE INDEX \`${u.name}\` (${u.cols})`));
  }
}
fs.writeFileSync("drizzle/0024_hot_indexes.sql", o2.join("\n") + "\n");
console.log("tables:", Object.keys(tables).length, "columns:", Object.values(tables).reduce((a, t) => a + t.cols.length, 0), "indexes:", kitIndexes.length, "inline uniques:", Object.values(tables).reduce((a, t) => a + t.uniques.length, 0));
